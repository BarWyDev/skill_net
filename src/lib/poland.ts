/** Ray casting on the plain lng/lat plane: at this scale the error is far below the outline's. */
export function isInPoland(lat: number, lng: number): boolean {
  let inside = false;
  for (let i = 0, j = POLAND_OUTLINE.length - 1; i < POLAND_OUTLINE.length; j = i++) {
    const [xi, yi] = POLAND_OUTLINE[i];
    const [xj, yj] = POLAND_OUTLINE[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
